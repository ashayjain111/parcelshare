CREATE TABLE region (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE city (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  state VARCHAR(80) NOT NULL,
  region_id BIGINT NOT NULL REFERENCES region(id),
  CONSTRAINT uq_city UNIQUE (name, state)
);
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  phone VARCHAR(20),
  full_name VARCHAR(120) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(20) NOT NULL,
  status VARCHAR(20) NOT NULL,
  email_verified BOOLEAN NOT NULL,
  verify_token VARCHAR(64),
  traveller_verification VARCHAR(20) NOT NULL,
  verification_note VARCHAR(500),
  rating_sum INT NOT NULL DEFAULT 0,
  rating_count INT NOT NULL DEFAULT 0,
  completed_deliveries INT NOT NULL DEFAULT 0,
  cancelled_count INT NOT NULL DEFAULT 0,
  disputed_count INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL
);
CREATE TABLE trip (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  traveller_id BIGINT NOT NULL REFERENCES users(id),
  origin_city_id BIGINT NOT NULL REFERENCES city(id),
  dest_city_id BIGINT NOT NULL REFERENCES city(id),
  departs_at TIMESTAMP NOT NULL,
  travel_mode VARCHAR(20) NOT NULL,
  capacity_grams INT NOT NULL,
  reserved_grams INT NOT NULL DEFAULT 0,
  price_per_kg_paise INT NOT NULL,
  status VARCHAR(20) NOT NULL,
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT ck_trip_capacity CHECK (reserved_grams >= 0 AND reserved_grams <= capacity_grams)
);
CREATE INDEX idx_trip_route ON trip (origin_city_id, dest_city_id, departs_at);
CREATE INDEX idx_trip_traveller ON trip (traveller_id);
CREATE TABLE parcel_category (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL UNIQUE,
  tier VARCHAR(20) NOT NULL,
  max_grams INT NOT NULL,
  max_value_paise BIGINT NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE blocked_keyword (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word VARCHAR(60) NOT NULL UNIQUE
);
CREATE TABLE parcel (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_code VARCHAR(20) NOT NULL UNIQUE,
  sender_id BIGINT NOT NULL REFERENCES users(id),
  origin_city_id BIGINT NOT NULL REFERENCES city(id),
  dest_city_id BIGINT NOT NULL REFERENCES city(id),
  window_start TIMESTAMP NOT NULL,
  window_end TIMESTAMP NOT NULL,
  category_id BIGINT NOT NULL REFERENCES parcel_category(id),
  weight_grams INT NOT NULL,
  description VARCHAR(500) NOT NULL,
  declared_value_paise BIGINT NOT NULL,
  recipient_name VARCHAR(120) NOT NULL,
  recipient_phone VARCHAR(20),
  status VARCHAR(20) NOT NULL,
  flag_reason VARCHAR(200),
  created_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_parcel_route ON parcel (origin_city_id, dest_city_id, window_start);
CREATE INDEX idx_parcel_sender ON parcel (sender_id);
CREATE TABLE booking (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id BIGINT NOT NULL REFERENCES trip(id),
  parcel_id BIGINT NOT NULL REFERENCES parcel(id),
  price_paise BIGINT NOT NULL,
  commission_paise BIGINT NOT NULL,
  status VARCHAR(20) NOT NULL,
  handover_hash VARCHAR(64),
  handover_expires_at TIMESTAMP,
  handover_attempts INT NOT NULL DEFAULT 0,
  delivery_attempts INT NOT NULL DEFAULT 0,
  recipient_token VARCHAR(40) NOT NULL UNIQUE,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_booking_trip ON booking (trip_id);
CREATE INDEX idx_booking_parcel ON booking (parcel_id);
CREATE INDEX idx_booking_status ON booking (status);
CREATE TABLE payment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL UNIQUE REFERENCES booking(id),
  amount_paise BIGINT NOT NULL,
  commission_paise BIGINT NOT NULL,
  status VARCHAR(30) NOT NULL,
  gateway VARCHAR(20) NOT NULL,
  gateway_ref VARCHAR(80),
  release_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL
);
CREATE TABLE ledger_entry (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id BIGINT NOT NULL REFERENCES payment(id),
  account VARCHAR(20) NOT NULL,
  direction VARCHAR(10) NOT NULL,
  amount_paise BIGINT NOT NULL,
  memo VARCHAR(120),
  created_at TIMESTAMP NOT NULL
);
CREATE TABLE tracking_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES booking(id),
  type VARCHAR(40) NOT NULL,
  actor_id BIGINT,
  payload VARCHAR(1000),
  prev_hash VARCHAR(64) NOT NULL,
  hash VARCHAR(64) NOT NULL,
  created_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_event_booking ON tracking_event (booking_id, id);
CREATE TABLE rating (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES booking(id),
  rater_id BIGINT NOT NULL REFERENCES users(id),
  ratee_id BIGINT NOT NULL REFERENCES users(id),
  score INT NOT NULL,
  comment VARCHAR(500),
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT uq_rating UNIQUE (booking_id, rater_id)
);
CREATE TABLE dispute (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES booking(id),
  raised_by BIGINT REFERENCES users(id),
  raised_by_role VARCHAR(20) NOT NULL,
  reason VARCHAR(1000) NOT NULL,
  status VARCHAR(20) NOT NULL,
  resolution VARCHAR(20),
  traveller_share_paise BIGINT,
  admin_note VARCHAR(1000),
  resolved_by BIGINT REFERENCES users(id),
  created_at TIMESTAMP NOT NULL,
  resolved_at TIMESTAMP
);
CREATE INDEX idx_dispute_status ON dispute (status);
CREATE TABLE audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT,
  action VARCHAR(60) NOT NULL,
  entity_type VARCHAR(40),
  entity_id BIGINT,
  detail VARCHAR(1000),
  created_at TIMESTAMP NOT NULL
);
