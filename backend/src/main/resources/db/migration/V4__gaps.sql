-- Password reset (only a hash of the emailed token is stored)
ALTER TABLE users ADD COLUMN reset_token_hash VARCHAR(64);
ALTER TABLE users ADD COLUMN reset_expires_at TIMESTAMP;

-- A traveller offering to carry a specific parcel (the sender still decides and pays)
CREATE TABLE parcel_offer (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id BIGINT NOT NULL REFERENCES trip(id),
  parcel_id BIGINT NOT NULL REFERENCES parcel(id),
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT uq_offer UNIQUE (trip_id, parcel_id)
);
CREATE INDEX idx_offer_parcel ON parcel_offer (parcel_id);

-- In-app notifications (the bell), written alongside the emails
CREATE TABLE notification (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  type VARCHAR(40) NOT NULL,
  title VARCHAR(160) NOT NULL,
  body VARCHAR(500),
  link VARCHAR(200),
  read_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_notification_user ON notification (user_id, id);
